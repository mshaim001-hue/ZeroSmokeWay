export function firstVisitQuestion(cell) {
  const lines = FIRST_VISIT[cell?.id] || FIRST_VISIT[cell?.internalName];
  if (lines) return lines.join('\n\n');
  const title = cell?.title || 'Эта клетка';
  return `${title}.\n\nВспомните последнюю сигарету, которая всплывает рядом с этим словом.\n\nЧто тогда происходило?`;
}
