/**
 * Возвращает текст правила "чем закончить ответ" для вставки в промпт агента.
 */
export function getUserNextStepRule(phase) {
  const rule = USER_NEXT_STEP_BY_PHASE[phase];
  return rule
    ? `\n\nЗАКОНЧИ ОТВЕТ ПРАВИЛОМ ДЛЯ ЭТОЙ ФАЗЫ: ${rule}`
    : '\n\nЗАКОНЧИ ОТВЕТ: чётким вопросом или коротким приглашением ответить, чтобы пользователь понимал, что делать дальше.';
}
